# Розглянемо собак та котів
# Ми знаємо що кіт та собака є тваринами та мають здітність створювати звуки. Хоч звуки можуть створювати
# і собаки і коти, ці звуки суттєво відрізняються одне від одного. Ми також можемо дресирувати домашніх
# тварин щоб вони робили певні звуки за командою, яка може бути однаковою для собаки і кота.
# Наприклад команда "Speak" та спільний спосіб надання команди для собак та кота можна назвати інтерфейсом
# взаємодії з ними. "Speak" - є спільним інтерфейсом для обробки команди.

"""Поліморфізм(polymorphism) - це один з основних принципів ООП, що дозволяє об'єктам різних класів оброблятися
через один інтерфейс. Це дає змогу методам, функціям та операторам виконувати операції з різними об'єктами та класами.

Переваги поліморфізму:
    - Гнучкість(Ми можемо визначити які звуки будуть присутні у різних об'єктах класу, не змінюючи інтерфейс взаємодії
    - Повторно використання коду
    - Зменшення складності
    - Масштабованість"""

class Animal:
    def __init__(self, name):
        self.name = name

    @staticmethod
    def speak():
        pass

class Dog(Animal):
    @staticmethod
    def speak():
        return "Woof"

class Cat(Animal):
    @staticmethod
    def speak():
        return "Meow"

if __name__ == "__main__":
    my_dog = Dog('Peter')
    my_cat = Cat('Garfield')

    my_animals = [my_dog, my_cat]
    for animal in my_animals:
        print(animal.speak())
