# Розглянемо квартиру у під'їзді. Під'їзд є загальнодоступний місцем, тому є певна інформація, котра доступна
# кожному відвідувачу під'їзду. Це наприклад номер квартири, показники лічильника, якщо він розташований
# ззовні та колір дверей. В той самий час є певна інформація котра не доступна. Наприклад кількість кімнат,
# дизайн інтер'єру, чи є телевізор. Але цю інформацію можуть дізнатись наприклад наші друзі, яких ми запрошуємо
# у нашу квартиру. Так вони можуть дізнатись що кількість кімнат - 3, дизайн інтер'єру - модерн, і також
# у квартирі є телевізор. Ця інформація не є початково доступною. Проте навіть гості  втой самий час не знають
# всі особливості квартири, наприклад чи є у квартирі сейф, що зберігається у сейфі та яка вартість квартири
# Без дозволу власників, наші гості не зможуть дізнатись всю інформацію. Той факт що у квартирі є сейф не має
# впливати на спілкування з друзями. Ми так само можемо дивитись телевізор. В той самий час дизайн квартири чи
# наявність телевізора не мають впливати на роботу інспекторів, котрі записують показники лічильників.
# Квартира як об'єт існує незалежно від того хто з нею взаємодіє(Гості, інспектор чи власники).

# Квартира є об'єктом, який створюється з певного класу(креслення цієї квартири). Ми заздалегідь визначаємо
# властивості квартири на рівні класу у вигляді атрибутів(номер квартири, наявність телевізора), методів(зчитування
# показників лічильнику, відкриття сейфу). Також ми називаємо будь-які сутності, що взаємодіють з об'єктом
# або класом - як клієнти. У випадку квартири клієнтами є інспектор, друзі, власники.

"""Інкапсуляція(encapsulation) - це один із основних принципів ООП, який полягає в об'єднанні даних(атрибутів)
та методів, що їх обробляють в єдинник об'єкт(клас)
    - Приховання внутрішніх деталей реалізації від клієнта
    - Взаємодія за допомогою заздалегідь визначених методів"""

# Реалізуємо клас квартири

class Flat:
    def __init__(self, number):
        self.number = number
        self.door_color = "Brown"
        self.electricity_readings = 0

    def display_number(self):
        print(f"Flat number is {self.number}")

if __name__ == "__main__":
    flat = Flat(212)

    flat.display_number() # Це публічний метод, який доступний зовні класу та і в дочірніх класах
    print(f"Flat has {flat.door_color} door color")
    print(f"Electricity readings for flat {flat.number}: {flat.electricity_readings}")

